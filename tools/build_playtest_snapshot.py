"""Capture a real-data snapshot for the LED playtest page (playtest/snapshot.js).

    .venv/bin/python -I tools/build_playtest_snapshot.py

The page loads this file when it cannot reach MET Norway directly (inside the
claude.ai artifact viewer, whose sandbox blocks other hosts).

Encoding: one byte per LED, row-major 64×64 per frame, value = mm/h × 10
(capped at 250), 255 = no radar coverage.
"""

import asyncio
import base64
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import httpx
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from cli_weather import basemap, grid  # noqa: E402
from cli_weather.source import BASE, USER_AGENT, Box, Source, parse_dods  # noqa: E402

SIZE = 64
BOX = Box(grid.STOCKHOLM[0] - SIZE // 2, grid.STOCKHOLM[1] - SIZE // 2, SIZE, SIZE)

# MET Nordic 1 km forecast: same Lambert projection, but rows run south→north
# and the origin is offset. Radar (row, col) → Nordic (2229 - row, col + 101), < 0.5 km apart.
NORDIC_PATH = "metpplatest/met_forecast_1_0km_nordic_latest.nc"
NORDIC_ROW_FLIP = 2229
NORDIC_COL_SHIFT = 101
NORDIC_STEPS = 56  # step 0 has no accumulation; 1..56 are hourly amounts (mm in the past hour)


def encode(frames: np.ndarray) -> str:
    q = np.where(np.isnan(frames), 255, np.clip(np.round(frames * 10), 0, 250)).astype(np.uint8)
    return base64.b64encode(q.tobytes()).decode()


async def nordic_forecast(client: httpx.AsyncClient) -> tuple[list[str], np.ndarray]:
    r_top = NORDIC_ROW_FLIP - BOX.row0  # northernmost radar row → highest Nordic row
    r_bot = NORDIC_ROW_FLIP - (BOX.row0 + SIZE - 1)
    c0 = BOX.col0 + NORDIC_COL_SHIFT
    q = f"precipitation_amount.precipitation_amount[1:{NORDIC_STEPS}][{r_bot}:{r_top}][{c0}:{c0 + SIZE - 1}]"
    url = f"{BASE}/dodsC/{NORDIC_PATH}.dods?" + q.replace("[", "%5B").replace("]", "%5D")
    resp = await client.get(url)
    resp.raise_for_status()
    data = parse_dods(resp.content, (NORDIC_STEPS, SIZE, SIZE))[:, ::-1, :]  # flip to north-up

    t = await client.get(f"{BASE}/dodsC/{NORDIC_PATH}.ascii?time%5B1:{NORDIC_STEPS}%5D")
    t.raise_for_status()
    seconds = [float(v) for v in t.text.split("time[")[-1].split("\n", 1)[1].strip().split(",")]
    times = [datetime.fromtimestamp(s, timezone.utc).isoformat() for s in seconds]
    return times, data


async def main() -> None:
    async with httpx.AsyncClient(headers={"User-Agent": USER_AGENT}, timeout=60.0) as client:
        source = Source(BOX, client)
        radar = await source.load_frames()
        f_times, f_data = await nordic_forecast(client)

    missing = np.full((SIZE, SIZE), np.nan, np.float32)
    radar_grid = np.stack([f.grid if f.grid is not None else missing for f in radar])
    base = basemap.load()
    land = base.window(BOX.row0, BOX.col0, SIZE, SIZE).astype(np.uint8)

    snapshot = {
        "capturedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "origin": [BOX.row0, BOX.col0],
        "radar": {
            "times": [f.time.isoformat() for f in radar],
            "offsets": [f.offset for f in radar],
            "frames": encode(radar_grid),
        },
        "forecast": {"times": f_times, "frames": encode(f_data)},
        "land": base64.b64encode(land.tobytes()).decode(),
    }
    out = ROOT / "playtest" / "snapshot.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text(
        "// Generated by tools/build_playtest_snapshot.py — real MET Norway data (CC BY 4.0).\n"
        f"window.STOCKHOLM_SNAPSHOT = {json.dumps(snapshot)};\n"
    )
    wet = [int((g >= 0.1).sum()) for g in radar_grid]
    print(f"wrote {out} ({out.stat().st_size // 1024} KB); radar wet LEDs per frame {wet[::6]}; "
          f"forecast max {np.nanmax(f_data):.1f} mm/h", file=sys.stderr)


if __name__ == "__main__":
    asyncio.run(main())
